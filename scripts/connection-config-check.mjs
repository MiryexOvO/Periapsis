// Isolated CLI checks; never reads or changes the operator's deployment configuration.
import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {execFileSync} from 'node:child_process';
const directory=fs.mkdtempSync(path.resolve('dist/connection-config-'));
const config=path.join(directory,'server.json');
const bin=path.resolve('target/release/peri-webtransport'+(process.platform==='win32'?'.exe':''));
const env={...process.env,PERI_CONFIG:config};
const run=(args,input)=>execFileSync(bin,args,{env,input,encoding:'utf8',windowsHide:true});
run(['setup'],'127.0.0.1\n\n\n\n\n\n');
const initial=fs.readFileSync(config,'utf8'),before=JSON.parse(initial);
assert.notEqual(before.stream_key,'stream');
assert(before.stream_key.length>=32);
assert(fs.existsSync(before.cert)&&fs.existsSync(before.key));
const initialLink=run(['link']);
const code=initialLink.split('Stream key: ')[1].trim();
assert(code.startsWith('peri1_'));
run(['setup']);
assert.equal(fs.readFileSync(config,'utf8'),initial);
run(['configure'],'192.0.2.10\n23927\n');
const updated=JSON.parse(fs.readFileSync(config));
assert.equal(updated.udp,before.udp);
assert.equal(updated.external,23927);
assert.equal(updated.cert,before.cert);
assert.equal(updated.key,before.key);
assert.deepEqual(updated.tokens,before.tokens);
const link=run(['link']);
assert(link.includes('peri://192.0.2.10:23927'));
assert.equal(link.split('Stream key: ')[1].trim(),code);
run(['stream-key']);
assert.notEqual(run(['link']).split('Stream key: ')[1].trim(),code);
assert.deepEqual(JSON.parse(fs.readFileSync(config)).tokens,before.tokens);
console.log('Connection configuration: automatic setup, existing-config preservation, address changes and key rotation OK');
